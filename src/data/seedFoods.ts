/** 外食で F・C・塩分が公表されていないときの推定ルール（v4 §5 の「—」を埋める） */
export const EATING_OUT_FAT_RATIO = 0.3
export const EATING_OUT_DEFAULT_SALT_G = 4.0

/** kcal と P だけ分かっている外食の1行を作る。F は kcal の30%、残りを C に置く。 */
function eatingOut(
  id: string,
  name: string,
  kcal: number,
  proteinG: number,
  opts: { fatG?: number; carbG?: number; saltG?: number } = {}
): Food {
  const estimated = opts.fatG == null || opts.carbG == null || opts.saltG == null
  const fatG = opts.fatG ?? Math.round(((kcal * EATING_OUT_FAT_RATIO) / 9) * 10) / 10
  const carbG =
    opts.carbG ?? Math.max(0, Math.round(((kcal - proteinG * 4 - fatG * 9) / 4) * 10) / 10)
  return {
    id,
    name,
    baseAmount: 1,
    baseUnit: '食',
    kcal,
    proteinG,
    fatG,
    carbG,
    saltG: opts.saltG ?? EATING_OUT_DEFAULT_SALT_G,
    category: 'eating_out',
    stepAmount: 1,
    maxAmount: 2,
    isEstimated: estimated || undefined,
    note: estimated
      ? '公表値が P とカロリーだけなので、脂質はカロリーの30%、塩分は4.0gで見積もっています'
      : undefined,
  }
}

